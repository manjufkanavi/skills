#!/usr/bin/env python3
"""cinematographer — offline, language-agnostic scene breakdown and 5-second video-prompt generator.

Takes natural-language text in ANY language (English, Kannada, Hindi, ...) and turns it into a
scene-by-scene breakdown plus ready-to-use 5-second video-generation prompts.

Two modes:

  MODE A — plot → structured plan (movie-maker integration).
    The AGENT performs the semantic planning pass in-model: it reads a plot and emits a structured
    plan (theme, characters with bibles, beats where each 5s scene attributes who says what).
    This script then assembles that plan deterministically into scenes.json with:

      * canonical subjects (from character identities, NOT sentence-split heuristics)
        — fixes the "auto scene-breaker is broken" bug where subjects became fragments like
          "Terrified, the animals agreed".
      * per-scene dialogue attribution ("who says what") — carried verbatim from the plan.
      * character consistency — every scene reuses ONE canonical Pixar-look prompt + fixed seed per
        character (generated by characters.py via disney-character-creator), so faces/hair/wardrobe
        don't drift shot-to-shot.
      * real continuity — a genuine shared visual_contract_id, computed carried palette/lighting that
        varies by emotion only, and actual 180°/30°/eyeline/matching-action shot rules.
      * Pixar-look video prompt — fixed schema + shared style-lock block appended identically to
        every scene, plus a per-beat model recommendation.

  MODE B — plain text (backward compatible).
    A single narration-only scene per sentence block. Kept for standalone use; the planner +
    character-consistency path (Mode A) is preferred.

No external LLM, no network — fully offline. The semantic understanding lives in the agent that
runs this skill; every function below is deterministic Python.

Usage:
    # Mode A — structured plan (movie-maker calls this)
    python3 main.py --plan path/to/plan.json [--max-scenes 12]

    # Mode B — plain text (backward compatible)
    python3 main.py --text "A woman walks into a rain-soaked alley."
    python3 main.py --file path/to/story.txt [--style cinematic] [--aspect 16:9]
"""

